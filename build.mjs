import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)));
const outputDirectory = path.join(packageRoot, "dist");
const fontsRoot = path.join(packageRoot, "node_modules", "@excalidraw", "excalidraw", "dist", "prod", "fonts");
// Excalifont is what diagrams draw with; Assistant is the editor UI font; Virgil renders older diagrams.
// Other families fall back to system fonts (Xiaolai alone is several MB).
const INLINE_FONT_FAMILIES = ["Excalifont", "Assistant", "Virgil"];

await rm(outputDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });

const fonts = {};
for (const family of INLINE_FONT_FAMILIES) {
  for (const file of await readdir(path.join(fontsRoot, family))) {
    if (file.endsWith(".woff2")) fonts[file] = (await readFile(path.join(fontsRoot, family, file))).toString("base64");
  }
}

const virtualFonts = {
  name: "excalidraw-fonts",
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /^virtual:excalidraw-fonts$/ }, () => ({ path: "fonts", namespace: "excalidraw-fonts" }));
    pluginBuild.onLoad({ filter: /.*/, namespace: "excalidraw-fonts" }, () => ({ contents: JSON.stringify(fonts), loader: "json" }));
  },
};

// Lazily loaded Excalidraw features the card never uses, stubbed so they are not inlined (they were
// ~6 MB of the 8.5 MB bundle): the Mermaid import dialog, non-English locales (the card renders "en",
// which is in the main chunk), and the WASM font subsetter used only by SVG export.
const STUBS = [
  { filter: /^@excalidraw\/mermaid-to-excalidraw$/, contents: 'export const parseMermaidToExcalidraw = async () => { throw new Error("Mermaid import is unavailable in this card."); };' },
  { filter: /^\.\/locales\//, contents: "export default {};" },
  { filter: /^\.\/subset-(shared|worker)\.chunk\.js$/, contents: 'throw new Error("Font subsetting is unavailable in this card.");' },
];
const optionalFeatures = {
  name: "excalidraw-optional-features",
  setup(pluginBuild) {
    STUBS.forEach((stub, index) => {
      pluginBuild.onResolve({ filter: stub.filter }, (args) =>
        args.importer.includes(`${path.sep}@excalidraw${path.sep}`) || stub.filter.source.startsWith("^@")
          ? { path: String(index), namespace: "excalidraw-stub" }
          : undefined,
      );
    });
    pluginBuild.onLoad({ filter: /.*/, namespace: "excalidraw-stub" }, (args) => ({ contents: STUBS[Number(args.path)].contents, loader: "js" }));
  },
};

const view = await build({
  entryPoints: [path.join(packageRoot, "src", "browser", "app.tsx")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  write: false,
  outdir: path.join(packageRoot, ".view"),
  jsx: "automatic",
  conditions: ["production"],
  define: { "process.env.NODE_ENV": '"production"', "process.env.IS_PREACT": '"false"', "import.meta.env": "{}" },
  loader: { ".woff2": "dataurl", ".png": "dataurl", ".svg": "dataurl" },
  plugins: [virtualFonts, optionalFeatures],
  // Excalidraw, React and other bundled licenses are listed in THIRD_PARTY_NOTICES.md.
  legalComments: "none",
  logLevel: "warning",
});
const viewScript = view.outputFiles.find((file) => file.path.endsWith(".js"))?.text;
// The card inherits Marshal's font-src 'self', which blocks these data: URLs; shims.ts registers the
// same Assistant weights from bytes instead.
const viewCss = (view.outputFiles.find((file) => file.path.endsWith(".css"))?.text ?? "").replace(/@font-face\{font-family:Assistant;[^}]*\}/g, "");
if (!viewScript) throw new Error("View bundle produced no script.");

const generatedDirectory = path.join(packageRoot, "src", "generated");
await mkdir(generatedDirectory, { recursive: true });
await writeFile(
  path.join(generatedDirectory, "viewAssets.ts"),
  [
    "// Generated by build.mjs — do not edit.",
    `export const VIEW_SCRIPT: string = ${JSON.stringify(viewScript)};`,
    `export const VIEW_CSS: string = ${JSON.stringify(viewCss)};`,
    "",
  ].join("\n"),
);

await build({
  entryPoints: [path.join(packageRoot, "src", "extension.ts")],
  outfile: path.join(outputDirectory, "runtime.cjs"),
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node20",
  packages: "bundle",
  sourcemap: false,
  legalComments: "eof",
  logLevel: "warning",
});

// The host copies the whole package root on install, so install from this folder (no node_modules or sources).
const stageDirectory = path.join(packageRoot, ".stage");
await rm(stageDirectory, { recursive: true, force: true });
await mkdir(path.join(stageDirectory, "dist"), { recursive: true });
for (const file of ["package.json", "runtime-extension.json", "README.md", "THIRD_PARTY_NOTICES.md", path.join("dist", "runtime.cjs")]) {
  await writeFile(path.join(stageDirectory, file), await readFile(path.join(packageRoot, file)));
}

const kb = (text) => `${Math.round(Buffer.byteLength(text) / 1024)} KB`;
console.log(`[excalidraw] view script ${kb(viewScript)}, css ${kb(viewCss)}, fonts ${Object.keys(fonts).length}; built dist/runtime.cjs`);
